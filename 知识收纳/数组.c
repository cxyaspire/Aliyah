/*
1、什么是数组？（136）
  C语言规定用方括号中的数字来表示下标，如s[15]
2、怎样定义和引用一维数组
 （1）定义：类型说明符 数组名[常量表达式] 
      数组名是一个地址常量，存放数组内存空间的首地址，本身就表示一个值
     下标是从0开始
 （2）引用：数组名[下标] 
      只能引用单个的数组元素，不能一次性引用整个数组
	  下标千万不能越位（>=数组长度）
 （3）一维数组的初始化（138）
      对所有元素赋初值：int a[5]={1,2,3,4,5};  如果对全部元素都赋初值，可以省略数组长度，但建议不要
	  部分元素的初始化：int a[5]={1,2};
	  #排序方法（140）
3、怎样定义和引用二维数组（矩阵）
（1）定义：类型说明符 数组名[常量表达式][常量表达式]
         二维数组按行存储
（2）引用：数组名[下标][下标]
（3）初始化（144）
      分行赋初值（建议使用）：int a[3][3]={{1,2,3},{4,5,6},{7,8,9}};
	  顺序赋初值：int a[3][3]={1,2,3,4,5,6,7,8,9};
	  省略行长度
（4）应用：1、通常将行下标作为外循环的循环变量，列下标作为内循环的循环变量
          2、矩阵与二维数组:主对角线i==j  上三角i<=j   下三角i>=j  副对角线i+j==N-1
4、字符数组
（1）定义：如c[0]=‘i’
（2）初始化与引用（148）
（3）结束标志:'\0'
 (4)输入输出:%c与%s
（5）使用字符串处理函数
     输入输出------puts函数、gets函数：只能输入或输出一个字符串
	 连接----------strcat(字符数组1，字符数组2)：字符数组1必须足够大
	 复制----------strcpy和strncpy函数：strcpy(字符数组1，字符串2） 字符数组1必须足够大
	 比较----------strcmp(字符串1，字符串2）：在英文字典中位置在后面的为"大"
	 测字符串长度--strlen(字符数组) 
 */
#include <stdio.h>
int main()
{
 int a[10];//定义数组
 int i,j,t;
 printf("input 10 numbers:\n");
 for(i=0;i<10;i++)
    scanf("%d",&a[i]);//把十个随机数值赋给十个数组
 printf("\n");
 for(j=0;j<9;j++)//进行9次循环，实现9趟比较 
   for(i=0;i<9-j;i++)//在每一趟中进行9-j次比较，起泡法！！！ 
     if(a[i]>a[i+1]) //相邻两个数比较
	 {t=a[i];a[i]=a[i+1];a[i+1]=t;}//交换值，升序排列
 printf("the sorted numbers：\n");
 for(i=0;i<10;i++)
   printf("%d\t",a[i]);
 printf("\n");
 return 0;
 } 
